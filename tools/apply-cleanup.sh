#!/usr/bin/env bash
# Applies the file removals and moves that come with an update ZIP.
#
# Unzipping over the project can add and replace files but never remove them,
# so each delivery lists here what became obsolete. Every step is idempotent:
# running this on every build is safe, and it does nothing once applied.
#
# Called by ~/rebuild.sh right after unzip:  bash tools/apply-cleanup.sh
set -e
cd "$(dirname "$0")/.."

# Deletes the given paths if they still exist.
remove() {
  for path in "$@"; do
    if [ -e "$path" ]; then
      rm -rf -- "$path"
      echo "cleanup: removed $path"
    fi
  done
}

# Moves a file or folder once; skipped when the source is gone.
move() {
  local from="$1" to="$2"
  if [ -e "$from" ]; then
    mkdir -p "$(dirname "$to")"
    if [ -e "$to" ]; then
      cp -a "$from"/. "$to"/ && rm -rf -- "$from"
    else
      mv -- "$from" "$to"
    fi
    echo "cleanup: moved $from -> $to"
  fi
}

# ---- Extensions migration (.OTips) -----------------------------------------
# Phases 1–2: nothing to remove.

# Phase 3 — Classifications become a bundled extension.
# Their figures move into the extension's source; Gradle packs it at build time.
move app/src/main/assets/classifications/images app/src/extensions/classifications/content/images
# The JSON now ships inside the ZIP under app/src/extensions/classifications/.
remove app/src/main/assets/classifications
# Bundled packages are generated by the build (packBundledExtensions), not committed.
remove app/src/main/assets/bundled_extensions
# Built-in classification/study data that nothing used any more.
remove app/src/main/java/com/example/data/local/ClinicalStudiesData.kt \
       app/src/main/java/com/example/data/local/model/ClinicalStudy.kt \
       app/src/main/java/com/example/ui/components/ClinicalStudyCard.kt

# Phase 4 — classification editor: nothing to remove.
# Phase 5 — encryption, validation, docs: nothing to remove.
# Bundled extensions are no longer installed automatically on first launch.
remove app/src/main/java/com/example/data/extensions/BundledExtensionDefaults.kt

echo "cleanup: done"
